async function extractErrors() {
  const hits = new Map();
  /** First site of any quoted upper-snake literal: covers codes thrown via
   * `fail('CODE', ...)` / `portableError('CODE', ...)`, which never use a
   * `code:` property and therefore are not part of the error-code count. */
  const literalSites = new Map();
  for (const file of walk("src")) {
    read(file)
      .split("\n")
      .forEach((line, index) => {
        for (const match of line.matchAll(/'([A-Z][A-Z0-9_]{2,})'/g)) {
          if (!literalSites.has(match[1]))
            literalSites.set(match[1], cite(file, index + 1));
        }
        for (const match of line.matchAll(ERROR_CODE)) {
          const code = match[2];
          if (!UPPER_CODE.test(code) && !NS_CODE.test(code)) continue;
          if (ERROR_NOT_CODES.has(code)) continue;
          if (!hits.has(code)) hits.set(code, []);
          hits.get(code).push(cite(file, index + 1));
        }
      });
  }
  const definitions = await import(
    pathToFileURL(abs("src/contracts/definitions.mjs")).href
  );
  const wire = Object.entries(definitions.STUDIO_WIRE_ERRORS).map(
    ([code, value]) => ({
      code,
      status: value.status,
      meaning: value.meaning,
      site: cite(
        "src/contracts/definitions.mjs",
        lineOf(
          "src/contracts/definitions.mjs",
          new RegExp(
            `(?:'${escapeRe(code)}'|\\b${escapeRe(code)}\\b)\\s*:`,
            "u",
          ),
        ),
      ),
    }),
  );
  const codes = new Map();
  for (const [code, sites] of hits) {
    const namespace = errorNamespace(code);
    codes.set(code, {
      code,
      namespace,
      site: sites[0],
      sites: sites.slice(0, 3),
      wire: wire.some((entry) => entry.code === code),
      meaning:
        ERROR_NAMESPACE_MEANING[namespace] ?? ERROR_NAMESPACE_MEANING.OTHER,
    });
  }
  for (const entry of wire) {
    if (!codes.has(entry.code)) {
      codes.set(entry.code, {
        code: entry.code,
        namespace: errorNamespace(entry.code),
        site: entry.site,
        sites: [entry.site],
        wire: true,
        meaning:
          ERROR_NAMESPACE_MEANING[errorNamespace(entry.code)] ??
          ERROR_NAMESPACE_MEANING.OTHER,
      });
    }
  }
  const groups = new Map();
  for (const entry of codes.values()) {
    if (!groups.has(entry.namespace)) groups.set(entry.namespace, []);
    groups.get(entry.namespace).push(entry);
  }
  return {
    total: codes.size,
    literalTotal: [...codes.values()].filter((entry) => !entry.wire).length,
    cancellationSite: cite(
      "src/contracts/definitions.mjs",
      lineOf("src/contracts/definitions.mjs", "STUDIO_CANCELLATION"),
    ),
    wire,
    wireTotal: wire.length,
    groups: [...groups]
      .sort(
        (a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0], "en"),
      )
      .map(([namespace, items]) => ({
        namespace,
        items: sorted(items.map((entry) => entry.code)),
        meaning:
          ERROR_NAMESPACE_MEANING[namespace] ?? ERROR_NAMESPACE_MEANING.OTHER,
        entries: items,
        site: sorted(items.map((entry) => entry.site))[0],
      })),
    byCode: codes,
    siteOf: (code) => codes.get(code)?.site ?? literalSites.get(code) ?? "—",
  };
}

