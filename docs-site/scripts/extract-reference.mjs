function extractCommands() {
  const lines = read("Makefile").split("\n");
  const targets = [];
  let comment = [];
  lines.forEach((line, index) => {
    if (/^#/.test(line)) {
      comment.push(line.replace(/^#\s?/, "").trim());
      return;
    }
    const match = /^([a-zA-Z0-9_.-]+):(.*)$/.exec(line);
    if (!match) {
      if (line.trim() !== "") comment = [];
      return;
    }
    const [, name, rest] = match;
    if (name === ".PHONY" || name.startsWith(".")) {
      comment = [];
      return;
    }
    const deps = rest.split("#")[0].trim().split(/\s+/).filter(Boolean);
    targets.push({ name, deps, comment: comment.join(" "), line: index + 1 });
    comment = [];
  });
  const allVerify = walk("scripts", /^verify-.*\.mjs$/);
  const verify = allVerify.map((file) => {
    const text = read(file);
    const block = /^\s*\/\*\*?([\s\S]*?)\*\//.exec(text);
    const first = text.split("\n").find((line) => /^\s*\/\//.test(line));
    const purpose = (block ? block[1] : (first ?? ""))
      .split("\n")
      .map((line) => line.replace(/^\s*\*?\s?/, "").trim())
      .filter(Boolean)
      .join(" ")
      .slice(0, 160);
    return { name: file.replace(/^scripts\//, ""), purpose };
  });
  // macOS ships Apple Silicon only. The `*-mac-x64` targets are historical
  // leftovers and are deliberately not part of the public reference.
  const LEGACY_TARGET = /-mac-x64/;
  const published = targets.filter(
    (target) => !LEGACY_TARGET.test(target.name),
  );
  const verifyGroups = new Map();
  for (const script of verify) {
    const segment = script.name.replace(/^verify-/, "").split("-")[0];
    if (!verifyGroups.has(segment)) verifyGroups.set(segment, []);
    verifyGroups.get(segment).push(script.name);
  }
  return {
    targets: published,
    excludedTargets: targets.length - published.length,
    targetTotal: published.length,
    scriptTotal: walk("scripts").length,
    verifyGroups: [...verifyGroups]
      .sort(
        (a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0], "en"),
      )
      .map(([segment, scripts]) => ({ segment, scripts: sorted(scripts) })),
    verify,
    verifyTotal: verify.length,
    verifyTopLevel: allVerify.filter((file) => file.split("/").length === 2)
      .length,
    defaultGoal: (() => {
      const match = /^\.DEFAULT_GOAL\s*:?=\s*(.+)$/m.exec(read("Makefile"));
      return match ? match[1].trim() : "";
    })(),
  };
}

