#!/usr/bin/env node
/**
 * Reference chapter generator.
 *
 * Every number, identifier and default in `content/docs/reference/**` is
 * extracted from source by this script. Nothing in the chapter is typed by
 * hand, so a source change that is not reflected here shows up as a dirty
 * working tree:
 *
 *     node scripts/extract-reference.mjs           # rewrite the 22 pages
 *     node scripts/extract-reference.mjs --check   # fail when they are stale
 *
 * Extraction is deliberately mechanical:
 *
 * | Source                                   | What is read                        |
 * | ---------------------------------------- | ----------------------------------- |
 * | `src/contracts/operations.mjs`            | operation ids (dynamic import)      |
 * | `src/host/routes/*.mjs`                   | operation handler `file:line`       |
 * | `src/**` `process.env.*` / `env.*`        | environment names + read sites      |
 * | `src/**` `code: '...'`                    | error codes + throw sites           |
 * | `Makefile`                                | targets, prerequisites, comments    |
 * | `scripts/verify-*.mjs`                    | gate scripts + leading comment      |
 * | `src/client/state/deployment.mjs`         | deployment states (dynamic import)   |
 * | `src/host/dsh-session-contract.mjs`       | session events + stream frames      |
 * | `src/runtime-contract.mjs`                | runtime/entity contract             |
 * | `src/team-template-contract.mjs`          | team template contract              |
 * | `src/product.json` + 3 manifests          | configuration keys                  |
 * | `src/dsh-plugin-catalog.mjs`              | plugin catalog schema + curated set |
 *
 * Values that are secrets, private hosts or internal model code names are
 * redacted at render time, never at extraction time, so the extractor stays a
 * faithful mirror of the source.
 */
