const abs = (path) => join(ROOT, path);
const read = (path) => readFileSync(abs(path), "utf8");

/** Repo-relative `file:line` string; used for every "开发者入口" citation. */
const cite = (path, line) => (line ? `${path}:${line}` : path);

function walk(dir, filter = /\.(?:mjs|js)$/) {
  const out = [];
  for (const name of readdirSync(abs(dir)).sort()) {
    const rel = join(dir, name);
    if (statSync(abs(rel)).isDirectory()) {
      if (name === "node_modules") continue;
      out.push(...walk(rel, filter));
    } else if (filter.test(name)) {
      out.push(rel);
    }
  }
  return out;
}

/** Line number (1-based) of the first match of `pattern` in a file. */
function lineOf(path, pattern) {
  const lines = read(path).split("\n");
  const re =
    typeof pattern === "string" ? new RegExp(escapeRe(pattern)) : pattern;
  for (let i = 0; i < lines.length; i += 1) if (re.test(lines[i])) return i + 1;
  return 0;
}

const escapeRe = (value) => value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const uniq = (values) => [...new Set(values)];
const sorted = (values) => [...values].sort((a, b) => a.localeCompare(b, "en"));

/** Markdown table. Pipes inside cells are escaped so codes never break a row. */
function table(headers, rows) {
  const cell = (value) =>
    String(value ?? "")
      .replace(/\|/g, "\\|")
      .replace(/\n+/g, " ")
      .trim();
  const head = `| ${headers.map(cell).join(" | ")} |`;
  const sep = `| ${headers.map(() => "---").join(" | ")} |`;
  return [
    head,
    sep,
    ...rows.map((row) => `| ${row.map(cell).join(" | ")} |`),
  ].join("\n");
}

const C = (value) => `\`${value}\``;
const codeList = (values) => values.map(C).join(" · ");

function page(title, description, body, lang = "zh") {
  const marker =
    lang === "zh"
      ? "{/* 本页由 docs-site/scripts/extract-reference.mjs 生成，请勿手工编辑。 */}"
      : "{/* Generated by docs-site/scripts/extract-reference.mjs. Do not edit by hand. */}";
  // Frontmatter is YAML: an unquoted description containing `: ` (common in
  // English prose) makes js-yaml read a nested mapping and fails the build.
  const yaml = (value) => JSON.stringify(String(value));
  return `---\ntitle: ${yaml(title)}\ndescription: ${yaml(description)}\n---\n\n${marker}\n\n${body.trim()}\n`;
}

