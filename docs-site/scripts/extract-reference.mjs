function extractEnvironment() {
  const names = new Map();
  const record = (name, file, kind) => {
    if (!names.has(name))
      names.set(name, { name, sites: new Set(), kinds: new Set() });
    const entry = names.get(name);
    entry.sites.add(file);
    entry.kinds.add(kind);
  };
  for (const file of walk("src")) {
    const text = read(file);
    for (const match of text.matchAll(ENV_READ)) record(match[1], file, "read");
    for (const match of text.matchAll(ENV_PROCESS))
      record(match[1] || match[2], file, "process");
    for (const match of text.matchAll(ENV_ARRAY))
      for (const item of match[2].matchAll(/['"]([A-Z][A-Z0-9_]{2,})['"]/g))
        record(item[1], file, "forward");
    for (const match of text.matchAll(ENV_SINGLE))
      record(match[1], file, "forward");
  }
  const entries = [...names.values()].map((entry) => ({
    name: entry.name,
    namespace: envNamespace(entry.name),
    tier:
      ENV_TIER_OVERRIDE[entry.name] ??
      (ENV_SECRET.test(entry.name)
        ? "forbidden"
        : ENV_PLATFORM.test(entry.name)
          ? "platform"
          : "configurable"),
    direct: entry.kinds.has("process"),
    forwarded: entry.kinds.has("forward"),
    sites: sorted(entry.sites).slice(0, 3),
    // Read only by the native-engine process provider, never by the public
    // runtimes: documented as an experimental knob. The name is deliberately
    // `experimental` so the public-surface host heuristic stays quiet.
    experimental:
      sorted(entry.sites).length === 1 &&
      sorted(entry.sites)[0] === "src/providers/native-engine-runtime.mjs",
  }))
    // Internal experimental knobs are not part of the public contract. Only the
    // experimental native-engine process provider reads them, and that runtime is
    // not documented in public (see STUDIO_RUNTIME_TYPES). Listing them here
    // would advertise a configuration surface users must not touch.
    .filter((entry) => !entry.experimental);
  const groups = new Map();
  for (const entry of entries) {
    if (!groups.has(entry.namespace)) groups.set(entry.namespace, []);
    groups.get(entry.namespace).push(entry);
  }
  return {
    total: entries.length,
    directTotal: entries.filter((entry) => entry.direct).length,
    forwardedTotal: entries.filter((entry) => entry.forwarded).length,
    processEnvReads: uniq(
      walk("src").flatMap((file) =>
        [...read(file).matchAll(ENV_PROCESS)].map(
          (match) => match[1] || match[2],
        ),
      ),
    ),
    entries: sorted(entries.map((entry) => entry.name)),
    groups: [...groups]
      .sort(
        (a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0], "en"),
      )
      .map(([namespace, items]) => ({ namespace, items })),
    byName: new Map(entries.map((entry) => [entry.name, entry])),
  };
}

