function redact(value) {
  return String(value)
    .replace(/[a-f0-9]{40,}/gi, "[commit-sha]")
    .replace(/https?:\/\/[^\s"']*ksyuncs[^\s"']*/g, "[release-origin]")
    .replace(/deepseek-v4[^\s"']*/g, "[internal-model-code]");
}

function extractConfiguration() {
  const product = JSON.parse(read("src/product.json"));
  const plugin = JSON.parse(read("studio.plugin.json"));
  const pin = JSON.parse(read("dsh-pin.json"));
  const patchLines = read("cordis.patch.yml").split("\n");
  const patches = [];
  let current = null;
  patchLines.forEach((line, index) => {
    const entry = /^- id:\s*(.+)$/.exec(line);
    if (entry) {
      current = {
        id: entry[1].trim(),
        disabled: null,
        name: "",
        config: [],
        insert: "",
        line: index + 1,
      };
      patches.push(current);
      return;
    }
    if (/^- insert:/.test(line)) {
      current = {
        id: "(insert)",
        disabled: null,
        name: "",
        config: [],
        insert: "",
        line: index + 1,
      };
      patches.push(current);
      return;
    }
    if (!current) return;
    const name = /^\s+name:\s*(.+)$/.exec(line);
    if (name) current.name = name[1].trim().replace(/^['"]|['"]$/g, "");
    const disabled = /^\s+disabled:\s*(true|false)$/.exec(line);
    if (disabled) current.disabled = disabled[1] === "true";
    const config = /^\s{4,}([A-Za-z][A-Za-z0-9_]*):\s*(.+)$/.exec(line);
    if (config && !/^(name|disabled|config)$/.test(config[1]))
      current.config.push(`${config[1]}=${config[2].trim()}`);
  });
  return {
    product,
    productFile: "src/product.json",
    plugin,
    pluginFile: "studio.plugin.json",
    pin: Object.fromEntries(
      Object.entries(pin).map(([key, value]) => [
        key,
        typeof value === "string" ? redact(value) : value,
      ]),
    ),
    pinFile: "dsh-pin.json",
    patches: patches.filter((entry) => entry.id !== "(insert)"),
    inserts: patches.filter((entry) => entry.id === "(insert)").length,
    patchFile: "cordis.patch.yml",
    patchCount: patches.filter((entry) => entry.id !== "(insert)").length,
  };
}

