/**
 * A bilingual cell. Rows are written once and localized at render time, so a
 * table can never exist with a Chinese note on the English page.
 */
const T = (zh, en) => ({ zh, en });
const pick = (value, lang) =>
  value !== null && typeof value === "object" ? value[lang] : value;

/** Markdown table with per-locale headers and cells. */
const bTable = (headers, rows, lang) =>
  table(
    headers.map((header) => pick(header, lang)),
    rows.map((row) => row.map((cell) => pick(cell, lang))),
  );

/** Section whose body is built once per locale. */
const secT = (zhHeading, enHeading, build) => ({
  heading: [zhHeading, enHeading],
  body: [build("zh"), build("en")],
});

function buildPage(lang, title, description, sections) {
  const index = lang === "zh" ? 0 : 1;
  const body = sections
    .filter(Boolean)
    .map((section) => (typeof section === "function" ? section(lang) : section))
    .map((section) => `## ${section.heading[index]}\n\n${section.body[index]}`)
    .join("\n\n");
  return page(title[index], description[index], body, lang);
}

const sourceTable = (rows, lang) =>
  bTable([T("内容", "Item"), T("源码位置", "Source")], rows, lang);
const testTable = (files, lang) =>
  bTable(
    [T("测试文件", "Test file"), T("位置", "Location")],
    files.map((file) => [file.replace(/^tests\//, ""), C(file)]),
    lang,
  );

/** `sources` entries are `[zhLabel, enLabel, path]`. */
function entrySection(sources, tests) {
  return (lang) => {
    const rows = sources.map(([zh, en, path]) => [T(zh, en), C(path)]);
    // Already localized, so both locales share the same two entries.
    const text = [
      sourceTable(rows, lang),
      "",
      lang === "zh" ? "相关测试：" : "Related tests:",
      "",
      testTable(tests, lang),
    ].join("\n");
    return {
      heading: ["开发者入口", "Developer entry points"],
      body: [text, text],
    };
  };
}

const versionSection = (rows) =>
  secT("版本与兼容性", "Version and compatibility", (lang) =>
    bTable([T("项", "Item"), T("值", "Value"), T("说明", "Notes")], rows, lang),
  );

