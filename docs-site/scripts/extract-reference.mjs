/** Action wording is derived, never curated per id: one verb table, 134 rows. */
function describeOperation(id, lang) {
  const [, ...rest] = id.split("/");
  const tail = rest.join("/");
  const verb = OPERATION_VERBS[tail] ?? OPERATION_VERBS[rest[0]];
  const index = lang === "zh" ? 0 : 1;
  return verb ? verb[index] : tail;
}

async function extractOperations() {
  const mod = await import(
    pathToFileURL(abs("src/contracts/operations.mjs")).href
  );
  const ids = [...mod.STUDIO_OPERATION_IDS];
  const known = new Set(ids);
  const handlers = new Map();
  const routeFiles = walk("src/host/routes");
  // Pass 1: routes that enumerate the id as a string literal. `routes/<domain>.mjs`
  // wins over a cross-cutting file (owner admission, HTTP wiring) that also
  // mentions the id, because the domain file is where the operation is served.
  const literalSites = [];
  for (const file of routeFiles) {
    read(file)
      .split("\n")
      .forEach((line, index) => {
        for (const match of line.matchAll(
          /['"]([a-z][a-z0-9-]*\/[a-zA-Z0-9-]+)['"]/g,
        )) {
          if (known.has(match[1]))
            literalSites.push({
              id: match[1],
              file,
              site: cite(file, index + 1),
            });
        }
      });
  }
  const dedicated = (id) => `src/host/routes/${id.split("/")[0]}.mjs`;
  for (const entry of literalSites.filter(
    (item) => item.file === dedicated(item.id),
  )) {
    if (!handlers.has(entry.id)) handlers.set(entry.id, entry.site);
  }
  for (const entry of literalSites) {
    if (!handlers.has(entry.id)) handlers.set(entry.id, entry.site);
  }
  // Pass 2: routes that dispatch a whole prefix (`endpoint.startsWith('deployments/')`).
  // A prefix whose branch throws is a retired surface: the id stays in the
  // contract so old clients get a typed error instead of a 404.
  const prefixes = [];
  for (const file of routeFiles) {
    const lines = read(file).split("\n");
    lines.forEach((line, index) => {
      const match = /startsWith\(\s*['"]([a-z][a-z0-9-]*\/[a-z0-9-]*)['"]/.exec(
        line,
      );
      if (!match) return;
      const retired = lines
        .slice(index, index + 3)
        .some((candidate) => /throw\b/.test(candidate));
      prefixes.push({ prefix: match[1], site: cite(file, index + 1), retired });
    });
  }
  prefixes.sort((a, b) => b.prefix.length - a.prefix.length);
  // Pass 3: routes that are a single payload-shaped function with no id switch.
  const overrides = {
    "host/computer": cite(
      "src/host/routes/host.mjs",
      lineOf("src/host/routes/host.mjs", "name: computer.hostname()"),
    ),
    "credentials/put": cite(
      "src/host/routes/credentials.mjs",
      lineOf("src/host/routes/credentials.mjs", "createCredentialRoute"),
    ),
  };
  const resolved = new Map();
  for (const id of ids) {
    if (handlers.has(id)) {
      resolved.set(id, { site: handlers.get(id), kind: "literal" });
      continue;
    }
    const prefix = prefixes.find((entry) => id.startsWith(entry.prefix));
    if (prefix) {
      resolved.set(id, {
        site: prefix.site,
        kind: prefix.retired ? "retired" : "prefix",
      });
      continue;
    }
    if (overrides[id]) {
      resolved.set(id, { site: overrides[id], kind: "literal" });
      continue;
    }
    resolved.set(id, {
      site: cite("src/contracts/operations.mjs", 0),
      kind: "contract",
    });
  }
  const domains = new Map();
  for (const id of ids) {
    const domain = id.split("/")[0];
    if (!domains.has(domain)) domains.set(domain, []);
    domains.get(domain).push(id);
  }
  return {
    total: ids.length,
    channel: mod.STUDIO_CONTROL_CHANNEL,
    channelSite: cite(
      "src/contracts/operations.mjs",
      lineOf("src/contracts/operations.mjs", "STUDIO_CONTROL_CHANNEL"),
    ),
    contractFile: cite(
      "src/contracts/operations.mjs",
      lineOf("src/contracts/operations.mjs", "STUDIO_OPERATION_IDS"),
    ),
    domains: [...domains].map(([name, operations]) => ({
      name,
      operations,
      summary: OPERATION_DOMAIN_SUMMARY[name] ?? ["", ""],
    })),
    handler: (id) =>
      resolved.get(id) ?? {
        site: cite("src/contracts/operations.mjs", 0),
        kind: "contract",
      },
    describe: describeOperation,
  };
}

