/**
 * Build Studio's bundled model-capability catalog from models.dev.
 *
 * The full api.json is ~7 MB and mostly prices and prose; Studio only needs
 * per-model reasoning levels, capacities and modalities, plus each provider's
 * display name and fixed endpoint. The shared compaction in
 * src/model-catalog-data/build.mjs (also used by the Host's background
 * refresh) shrinks it to a few hundred KB.
 *
 * Usage: node scripts/build-model-catalog.mjs [path-or-url-to-api.json]
 *        node scripts/build-model-catalog.mjs --check   # CI freshness gate
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { buildCapabilityCatalog } from '../src/model-catalog-data/build.mjs';

const check = process.argv.includes('--check');
const source = process.argv.slice(2).find(argument => !argument.startsWith('--')) || 'https://models.dev/api.json';
const isHttp = value => typeof value === 'string' && /^https?:\/\//.test(value);
const api = isHttp(source)
  ? await (await fetch(source)).json()
  : JSON.parse(await readFile(source, 'utf8'));

const catalog = buildCapabilityCatalog(api);
const modelCount = Object.values(catalog).reduce((total, group) => total + Object.keys(group.models).length, 0);
const generatedAt = new Date().toISOString();
const banner = `// Generated by scripts/build-model-catalog.mjs from models.dev on ${generatedAt}.\n`
  + `// ${Object.keys(catalog).length} providers, ${modelCount} models. Do not edit by hand.\n`;
const body = `export const MODEL_CATALOG_GENERATED_AT = ${JSON.stringify(generatedAt)};\n`
  + `export const MODEL_CATALOG = ${JSON.stringify(catalog)};\n`;
const dir = new URL('../src/model-catalog-data/', import.meta.url);
if (check) {
  // Compare only the data: a fresh fetch always differs by the generated-at
  // line, so the gate would never pass if it compared the whole file.
  const current = await readFile(new URL('catalog.mjs', dir), 'utf8').catch(() => '');
  const dataOf = text => text.slice(text.indexOf('export const MODEL_CATALOG = '));
  if (dataOf(current) !== dataOf(body)) {
    console.error('model capability catalog is stale; run: node scripts/build-model-catalog.mjs');
    process.exit(1);
  }
  console.log(`model capability catalog is up to date (${Object.keys(catalog).length} providers, ${modelCount} models)`);
} else {
  await mkdir(dir, { recursive: true });
  await writeFile(new URL('catalog.mjs', dir), banner + body);
  console.log(`providers=${Object.keys(catalog).length} models=${modelCount} bytes=${(banner + body).length}`);
}
