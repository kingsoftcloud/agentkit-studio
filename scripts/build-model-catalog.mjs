/**
 * Build Studio's bundled model-capability catalog from models.dev.
 *
 * The full api.json is ~7 MB and mostly prices and prose; Studio only needs
 * per-model reasoning levels, capacities and modalities, plus each provider's
 * display name and fixed endpoint. The shared compaction in
 * src/model-catalog-data/build.mjs (also used by the Host's background
 * refresh) shrinks it to a few hundred KB.
 *
 * Usage: node scripts/build-model-catalog.mjs [path-or-url-to-api.json]
 *        node scripts/build-model-catalog.mjs --check [pinned-api.json]
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { buildCapabilityCatalog } from '../src/model-catalog-data/build.mjs';

const check = process.argv.includes('--check');
const source = process.argv.slice(2).find(argument => !argument.startsWith('--'));
const dir = new URL('../src/model-catalog-data/', import.meta.url);
const output = new URL('catalog.mjs', dir);
const committed = check ? await import(output) : null;
const generatedAt = committed?.MODEL_CATALOG_GENERATED_AT ?? new Date().toISOString();
let catalog;
if (check && !source) {
  // CI validates the committed snapshot without depending on the published
  // catalog changing between builds. Pass a pinned source to check its data.
  catalog = committed.MODEL_CATALOG;
} else {
  const input = source || 'https://models.dev/api.json';
  if (/^https?:\/\//.test(input)) {
    const response = await fetch(input);
    if (!response.ok) throw Error(`Model catalog download failed (${response.status})`);
    catalog = buildCapabilityCatalog(await response.json());
  } else {
    catalog = buildCapabilityCatalog(JSON.parse(await readFile(input, 'utf8')));
  }
}
const providerCount = Object.keys(catalog).length;
const modelCount = Object.values(catalog).reduce((total, group) => total + Object.keys(group.models).length, 0);
if (!providerCount || !modelCount || new Date(generatedAt).toISOString() !== generatedAt)
  throw Error('Invalid model capability catalog snapshot');
const contents = `// Generated by scripts/build-model-catalog.mjs from models.dev on ${generatedAt}.\n`
  + `// ${providerCount} providers, ${modelCount} models. Do not edit by hand.\n`
  + `export const MODEL_CATALOG_GENERATED_AT = ${JSON.stringify(generatedAt)};\n`
  + `export const MODEL_CATALOG = ${JSON.stringify(catalog)};\n`;
if (check) {
  if (await readFile(output, 'utf8') !== contents) {
    console.error('model capability catalog is stale; run: node scripts/build-model-catalog.mjs');
    process.exit(1);
  }
  console.log(`model capability catalog is up to date (${providerCount} providers, ${modelCount} models)`);
} else {
  await mkdir(dir, { recursive: true });
  await writeFile(output, contents);
  console.log(`providers=${providerCount} models=${modelCount} bytes=${contents.length}`);
}
