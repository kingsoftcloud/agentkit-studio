/**
 * Build Studio's bundled model-capability catalog from models.dev.
 *
 * The full api.json is ~7 MB and mostly prices and prose; Studio only needs
 * per-model reasoning levels, capacities and modalities, plus each provider's
 * display name and fixed endpoint. Keeping just those fields (and only models
 * that carry any of them) shrinks the bundle to a few hundred KB.
 *
 * Usage: node scripts/build-model-catalog.mjs [path-or-url-to-api.json]
 */
import { readFile, writeFile, mkdir } from 'node:fs/promises';

// models.dev uses 99999999 as an "unlimited / unpublished" sentinel.
const UNLIMITED = 99_999_999;
const capacity = value => (Number.isSafeInteger(value) && value > 0 && value < UNLIMITED ? value : undefined);
const isHttp = value => typeof value === 'string' && /^https?:\/\//.test(value);

const source = process.argv[2] || 'https://models.dev/api.json';
const api = typeof source === 'string' && isHttp(source)
  ? await (await fetch(source)).json()
  : JSON.parse(await readFile(source, 'utf8'));

const catalog = {};
let modelCount = 0;
for (const [key, block] of Object.entries(api)) {
  const models = block?.models;
  if (!models || typeof models !== 'object') continue;
  const providerId = typeof block.id === 'string' ? block.id : key;
  const group = {
    ...(block.name ? { name: block.name } : {}),
    // A templated endpoint (https://api.{region}…) is not matchable; keep only fixed ones.
    ...(isHttp(block.api) && !block.api.includes('{') ? { api: block.api.replace(/\/$/, '') } : {}),
    models: {},
  };
  for (const [id, m] of Object.entries(models)) {
    if (!m || typeof m !== 'object') continue;
    const efforts = [];
    let toggle = false;
    for (const option of m.reasoning_options || []) {
      if (option?.type === 'toggle') toggle = true;
      if (option?.type === 'effort' && Array.isArray(option.values)) {
        for (const value of option.values) if (typeof value === 'string' && value) efforts.push(value);
      }
    }
    const context = capacity(m.limit?.context);
    const output = capacity(m.limit?.output);
    const image = Array.isArray(m.modalities?.input) && m.modalities.input.includes('image');
    const reasoning = m.reasoning === true && (toggle || efforts.length > 0);
    // Keep only models that tell us something Studio cannot infer on its own.
    if (!reasoning && context === undefined && output === undefined && !image) continue;
    group.models[id] = {
      ...(m.name && m.name !== id ? { name: m.name } : {}),
      ...(context !== undefined ? { context } : {}),
      ...(output !== undefined ? { output } : {}),
      ...(reasoning && efforts.length ? { efforts: [...new Set(efforts)] } : {}),
      ...(reasoning && toggle ? { toggle: true } : {}),
      ...(image ? { image: true } : {}),
    };
    modelCount += 1;
  }
  if (Object.keys(group.models).length) catalog[providerId] = group;
}

const generatedAt = new Date().toISOString();
const banner = `// Generated by scripts/build-model-catalog.mjs from models.dev on ${generatedAt}.\n`
  + `// ${Object.keys(catalog).length} providers, ${modelCount} models. Do not edit by hand.\n`;
const body = `export const MODEL_CATALOG_GENERATED_AT = ${JSON.stringify(generatedAt)};\n`
  + `export const MODEL_CATALOG = ${JSON.stringify(catalog)};\n`;
const dir = new URL('../src/model-catalog-data/', import.meta.url);
await mkdir(dir, { recursive: true });
await writeFile(new URL('catalog.mjs', dir), banner + body);
console.log(`providers=${Object.keys(catalog).length} models=${modelCount} bytes=${(banner + body).length}`);
