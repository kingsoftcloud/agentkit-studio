import test from 'node:test';
import assert from 'node:assert/strict';

import { CREDENTIAL_REF_PATTERN, deriveCredentialRefName, deriveCredentialReference, isCredentialRefName, normalizeMcpCredentialBindings } from '../src/credential-ref.mjs';
import { modelCredentialName } from '../src/client/dsh/model-bridge.mjs';
import { syncGlobalModelCredential } from '../src/model-credential-sync.mjs';
import { resolveMcpConnection } from '../src/local-resource-adapters.mjs';

test('an MCP header name yields a reference the DSH store can address', () => {
  // MCP secrets are named after headers (`X-KIP-Token`) and referenced as
  // `env://<name>`; the credential store only accepts POSIX identifiers.
  assert.equal(deriveCredentialRefName('X-KIP-Token'), 'X_KIP_Token');
  assert.equal(deriveCredentialRefName('AGENTKIT_MODEL_API_KEY'), 'AGENTKIT_MODEL_API_KEY');
  assert.equal(deriveCredentialRefName('9lives'), '_9lives');
  assert.equal(deriveCredentialRefName('ksyun/model key'), 'ksyun_model_key');
  assert.equal(deriveCredentialRefName('---', 'MCP_CREDENTIAL'), 'MCP_CREDENTIAL');
  assert.ok(isCredentialRefName(deriveCredentialRefName('X-KIP-Token')));
  // Deterministic: two spellings of the same header collapse to one reference,
  // so a re-save keeps pointing at the secret that was stored the first time.
  assert.equal(deriveCredentialRefName('X-KIP-Token'), deriveCredentialRefName('X_KIP_Token'));
  assert.equal(deriveCredentialReference('env://X-KIP-Token'), 'env://X_KIP_Token');
  assert.equal(deriveCredentialReference('X-KIP-Token'), 'env://X_KIP_Token');
});

test('stored model credential names are never rewritten', () => {
  // A stored name is already referenced by the profile, so rewriting it here
  // would orphan that reference; the write path refuses it instead.
  assert.equal(modelCredentialName({ credentialName: 'X-KIP-Token' }), 'X-KIP-Token');
  assert.equal(modelCredentialName({ credentialName: 'AGENTKIT_MODEL_API_KEY' }), 'AGENTKIT_MODEL_API_KEY');
  // Derived names are generated by Studio, so they are safe to keep addressable.
  const derived = modelCredentialName({ id: 'custom:vision' });
  assert.equal(derived, 'AGENTKIT_MODEL_API_KEY_CUSTOM_VISION');
  assert.ok(CREDENTIAL_REF_PATTERN.test(derived));
});

test('the host sync skips an unaddressable profile name instead of copying or renaming it', async () => {
  const written = [];
  const credentials = {
    resolve: async () => ({ source: 'memory', value: undefined }),
    set: async (name, value) => { written.push([name, value]); },
    describe: async name => ({ source: 'memory', name }),
  };
  const configuration = { resolve: async () => ({ values: {
    modelProfiles: [{ credentialName: 'X-KIP-Token', apiKey: 'not-a-real-key' }, { credentialName: 'AGENTKIT_MODEL_API_KEY_ALT', apiKey: 'junk' }],
  }, sources: {} }) };
  const summary = await syncGlobalModelCredential({ configuration, credentials });
  assert.deepEqual(written.map(([name]) => name), ['AGENTKIT_MODEL_API_KEY_ALT'], 'the bad name must not be written, and must not be renamed into a different secret');
  assert.deepEqual(summary.skipped, ['X-KIP-Token']);
  for (const [name] of written) assert.ok(CREDENTIAL_REF_PATTERN.test(name));
});

test('an MCP header credential is bound to a derived reference and stored under it', () => {
  // The header keeps its spelling as the key; only the reference side changes,
  // and both sides are written together, so nothing is orphaned.
  const bindings = normalizeMcpCredentialBindings({
    envRefs: { 'X-KIP-Token': 'env://X-KIP-Token', 'X-Trace': 'plain-value' },
    credentialName: 'X-KIP-Token',
    credentialValues: { 'X-KIP-Token': 'token-value' },
    requiredCredentials: [{ name: 'X-KIP-Token', header: 'X-KIP-Token' }],
  });
  assert.equal(bindings.credentialName, 'X_KIP_Token');
  assert.deepEqual(bindings.envRefs, { 'X-KIP-Token': 'env://X_KIP_Token', 'X-Trace': 'plain-value' });
  assert.deepEqual(bindings.writes, [['X_KIP_Token', 'token-value']]);
  for (const key of Object.keys(bindings.envRefs)) assert.ok(key === 'X-Trace' || CREDENTIAL_REF_PATTERN.test(bindings.envRefs[key].slice(6)));
});

test('the header the MCP server validates keeps its exact name on the wire', async () => {
  // The server authenticates on `X-KIP-Token`, so that header name must survive
  // the save verbatim; only the credential reference behind it is derived.
  const bindings = normalizeMcpCredentialBindings({
    envRefs: { 'X-KIP-Token': 'env://X-KIP-Token' },
    credentialValues: { 'X-KIP-Token': 'plain-token' },
    requiredCredentials: [{ name: 'X-KIP-Token', header: 'X-KIP-Token' }],
  });
  assert.deepEqual(bindings.envRefs, { 'X-KIP-Token': 'env://X_KIP_Token' }, 'the header keeps its spelling, the reference is derived');
  const credentials = {
    resolve: async name => (name === 'X_KIP_Token' ? { value: 'plain-token' } : undefined),
  };
  const { headers } = await resolveMcpConnection({ resourceId: 'kip', endpoint: 'https://kip.example.test/mcp', envRefs: bindings.envRefs }, credentials, {});
  assert.deepEqual(headers, { 'X-KIP-Token': 'plain-token' }, 'the outbound request still carries X-KIP-Token');
});
